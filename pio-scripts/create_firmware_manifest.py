"""Publish provenance without changing the commit identity embedded in OTA images."""
import datetime
import hashlib
import json
import os
import pathlib

from firmware_provenance import provenance


def create_manifest(dist, repository, channel, branch, identities):
    builds = {}
    for path in sorted(dist.glob('opendtu-hems-*.bin')):
        environment = path.name[len('opendtu-hems-'):-len('.bin')]
        md5 = hashlib.md5()
        sha256 = hashlib.sha256()
        with path.open('rb') as fp:
            while chunk := fp.read(1024 * 1024):
                md5.update(chunk)
                sha256.update(chunk)
        builds[environment] = {
            'file': path.name,
            'size': path.stat().st_size,
            'md5': md5.hexdigest(),
            'sha256': sha256.hexdigest(),
        }
    return {
        'schema': 'opendtu-hems-update/v1',
        'repository': repository,
        'channel': channel,
        'branch': branch,
        **identities,
        'published_at': datetime.datetime.now(datetime.timezone.utc).isoformat(timespec='seconds').replace('+00:00', 'Z'),
        'builds': builds,
    }


def main():
    dist = pathlib.Path(os.environ['DIST'])
    identities = provenance(os.environ['GITHUB_SHA'])
    manifest = create_manifest(dist, os.environ['UPDATE_REPOSITORY'], os.environ['CHANNEL_ID'],
                               os.environ['SOURCE_BRANCH'], identities)
    with (dist / 'manifest.json').open('w', encoding='utf-8') as fp:
        json.dump(manifest, fp, indent=2, sort_keys=True)
        fp.write('\n')
    (dist / 'README.md').write_text(
        '# Generated firmware update channel\n\n'
        f"Source branch: `{manifest['branch']}`  \n"
        f"Source commit: `{manifest['source_commit']}`  \n"
        f"Tested merge commit: `{manifest['tested_merge_commit']}`  \n"
        f"Image/build commit: `{manifest['commit']}`  \n"
        f"Update channel: `{manifest['channel']}`\n\n"
        'This branch is generated by GitHub Actions and force-replaced on each successful build.\n',
        encoding='utf-8',
    )


if __name__ == '__main__':
    main()
